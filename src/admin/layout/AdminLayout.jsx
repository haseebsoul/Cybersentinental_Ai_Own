import { useState } from "react";
import Sidebar from "./Sidebar";
import Topbar from "./Topbar";

import Dashboard from "../dashboard/Dashboard";
import Threats from "../threats/Threats";
import Events from "../events/Events";
import IPReputation from "../ip-reputation/IPReputation";
import Simulator from "../simulator/Simulator";
import Rules from "../rules/Rules";
import Logs from "../logs/Logs";
import Users from "../users/Users";
import Settings from "../settings/Settings";

import "./AdminLayout.css";

const pageMeta = {
  dashboard: {
    title: "Security Dashboard",
    subtitle: "Live overview of CyberSentinel-AI security operations",
  },
  threats: {
    title: "Threat Monitoring",
    subtitle: "Inspect detected threats and security responses",
  },
  events: {
    title: "Security Events",
    subtitle: "Review activity generated by the security pipeline",
  },
  "ip-reputation": {
    title: "IP Reputation",
    subtitle: "Analyze source IP activity and risk indicators",
  },
  simulator: {
    title: "Attack Simulator",
    subtitle: "Run controlled security scenarios in the demo environment",
  },
  rules: {
    title: "Security Rules",
    subtitle: "Manage detection rules used by the security engine",
  },
  logs: {
    title: "Security Logs",
    subtitle: "Review structured security and administrative records",
  },
  users: {
    title: "User Management",
    subtitle: "Manage users and application roles",
  },
  settings: {
    title: "System Settings",
    subtitle: "Configure platform preferences and monitoring behavior",
  },
};

function AdminLayout({
  session,
  activeModule,
  onNavigate,
  onLogout,
}) {
  const [sidebarOpen, setSidebarOpen] = useState(false);

  const currentPage = pageMeta[activeModule] || pageMeta.dashboard;

  const renderModule = () => {
    switch (activeModule) {
      case "threats":
        return <Threats />;

      case "events":
        return <Events />;

      case "ip-reputation":
        return <IPReputation />;

      case "simulator":
        return <Simulator />;

      case "rules":
        return <Rules />;

      case "logs":
        return <Logs />;

      case "users":
        return <Users />;

      case "settings":
        return <Settings />;

      case "dashboard":
      default:
        return <Dashboard />;
    }
  };

  const handleNavigation = (module) => {
    onNavigate(module);
    setSidebarOpen(false);
  };

  return (
    <div className="admin-layout">
      <Sidebar
        activeModule={activeModule}
        sidebarOpen={sidebarOpen}
        onNavigate={handleNavigation}
      />

      {sidebarOpen && (
        <button
          type="button"
          className="admin-sidebar-overlay"
          aria-label="Close navigation"
          onClick={() => setSidebarOpen(false)}
        />
      )}

      <div className="admin-main">
        <Topbar
          session={session}
          pageTitle={currentPage.title}
          onMenuClick={() => setSidebarOpen((value) => !value)}
          onLogout={onLogout}
        />

        <main className="admin-content">
          <div className="admin-content-header">
            <div>
              <div className="admin-breadcrumb">
                CyberSentinel-AI
                <span>/</span>
                Admin
                <span>/</span>
                {currentPage.title}
              </div>

              <h1>{currentPage.title}</h1>

              <p>{currentPage.subtitle}</p>
            </div>

            <div className="admin-mode-pill">
              <span className="mode-dot" />
              Frontend Prototype
            </div>
          </div>

          {renderModule()}
        </main>
      </div>
    </div>
  );
}

export default AdminLayout;